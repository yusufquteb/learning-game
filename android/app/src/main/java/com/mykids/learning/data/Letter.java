package com.mykids.learning.data;

public class Letter {
    public final String letter;
    public final String name;
    public final String word;
    public final String emoji;

    public Letter(String letter, String name, String word, String emoji) {
        this.letter = letter;
        this.name = name;
        this.word = word;
        this.emoji = emoji;
    }
}
